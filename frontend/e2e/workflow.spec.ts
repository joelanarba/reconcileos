import { expect, test } from '@playwright/test'
import path from 'node:path'
import { readFile } from 'node:fs/promises'

test('real CSV import, validation, reconciliation, filters, and source evidence', async ({ page }) => {
  test.setTimeout(90000)
  const browserErrors: string[] = []
  page.on('pageerror', error => browserErrors.push(error.message))
  await page.goto('/imports')
  await expect(page.getByRole('heading', { name: 'Imports', exact: true })).toBeVisible()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('link', { name: 'Download orders template' }).click()
  expect((await downloadPromise).suggestedFilename()).toBe('orders-template.csv')
  await page.getByLabel('Select a file').setInputFiles(path.resolve('../sample-data/slice1/invalid-orders.csv'))
  await page.getByRole('button', { name: 'Preview file' }).click()
  await expect(page.getByText('1 row needs attention before confirmation.')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Confirm import' })).toBeDisabled()
  for (const source of ['orders', 'payments', 'settlements']) {
    await page.getByLabel('Record type').selectOption(source)
    await page.getByLabel('Select a file').setInputFiles(path.resolve(`../sample-data/demo/${source}.csv`))
    await page.getByRole('button', { name: 'Preview file' }).click()
    await expect(page.locator('.preview-panel').getByText(`${source}.csv`, { exact: true })).toBeVisible()
    const confirmation = page.getByRole('button', { name: 'Confirm import' })
    if (await confirmation.count()) await confirmation.click()
    await expect(page.getByRole('button', { name: 'Imported', exact: true })).toBeVisible()
  }
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Reconciliation' }).click()
  await page.getByRole('button', { name: 'Start reconciliation' }).click()
  await expect(page).toHaveURL(/\/reconciliation\?run=[a-f0-9-]+$/)
  await expect(page.getByRole('button', { name: 'Start reconciliation', exact: true })).toBeEnabled()
  await expect(page.getByText('GHS 11,228.00', { exact: true })).toBeVisible()
  await expect(page.getByText('GHS 13,868.00', { exact: true })).toBeVisible()
  await expect(page.getByText('GHS 5,153.00', { exact: true })).toBeVisible()
  await expect(page.getByRole('tab', { name: 'Review cases 54' })).toBeVisible()
  await page.getByLabel('Discrepancy type').selectOption('partial_payment')
  await expect(page.getByText('5 results', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'View evidence' }).first().click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('dialog').locator('.source-identity').getByText(/SYN-ORD-008[1-5]/).first()).toBeVisible()
  await page.getByRole('button', { name: 'Close evidence' }).click()
  await page.getByRole('tab', { name: 'Accepted relationships 159' }).click()
  await page.getByRole('textbox', { name: 'Search references' }).fill('SYN-TXN-0003')
  await expect(page.getByRole('cell', { name: 'SYN-TXN-0003', exact: true }).first()).toBeVisible()
  await page.getByRole('button', { name: 'View evidence' }).first().click()
  await page.screenshot({ path: 'test-results/evidence-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Close evidence' }).click()
  await page.getByRole('tab', { name: 'Review cases 54' }).click()
  await page.getByRole('textbox', { name: 'Search references' }).fill('')
  await page.screenshot({ path: 'test-results/reconciliation-desktop.png', fullPage: true })
  await page.reload()
  await expect(page.getByText('GHS 11,228.00', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Dashboard', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Dashboard', exact: true })).toBeVisible()
  await expect(page.getByText('GHS 11,228.00', { exact: true })).toBeVisible()
  await expect(page.getByText('GHS 11,271.15', { exact: true })).toBeVisible()
  const dashboard = await (await page.request.get('http://127.0.0.1:8011/api/dashboard')).json()
  expect(dashboard.latest_run.current_summary.unresolved_discrepancy_count).toBe(54)
  await page.screenshot({ path: 'test-results/dashboard-desktop.png', fullPage: true })
  await page.getByRole('link', { name: 'Investigations', exact: true }).click()
  await page.getByRole('textbox', { name: 'Search investigation references' }).fill('SYN-TXN-0086')
  await page.getByRole('button', { name: 'Investigate', exact: true }).click()
  const panel = page.locator('.case-panel')
  const reason = page.getByRole('textbox', { name: 'Reason or investigation note' })
  await reason.fill('Checked the synthetic statement and incorrect reference.')
  await panel.getByRole('button', { name: 'Add note', exact: true }).click()
  await expect(panel.locator('.history-entry').filter({ hasText: 'Checked the synthetic statement' }).first()).toBeVisible()
  await reason.fill('The recorded equal amounts and source evidence support this association.')
  await page.getByLabel('Proposed association', { exact: true }).selectOption({ index: 1 })
  await page.getByRole('button', { name: 'Approve association', exact: true }).click()
  await expect(panel.locator('.manual-match')).toHaveCount(1)
  await reason.fill('Investigation disposition documented for the synthetic case.')
  await panel.getByRole('button', { name: 'Resolve case', exact: true }).click()
  await expect(panel.locator('.panel-heading .badge')).toHaveText('resolved')
  await reason.fill('Reopened to demonstrate explicit review history.')
  await panel.getByRole('button', { name: 'Reopen case', exact: true }).click()
  await expect(panel.locator('.panel-heading .badge')).toHaveText('reopened')
  await reason.fill('Reverse the demonstration association while preserving its history.')
  await panel.getByRole('button', { name: 'Reverse association', exact: true }).click()
  await expect(panel.locator('.manual-match')).toHaveCount(0)
  await page.reload()
  await expect(panel.locator('.history-entry').filter({ hasText: 'Reverse the demonstration association' }).first()).toBeVisible()
  await page.screenshot({ path: 'test-results/investigation-desktop.png', fullPage: true })
  await page.getByRole('link', { name: 'Reports', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Reports', exact: true })).toBeVisible()
  const summaryDownload = page.waitForEvent('download')
  await page.getByRole('link', { name: 'Export summary CSV' }).click()
  const downloaded = await summaryDownload
  expect(downloaded.suggestedFilename()).toContain('-summary.csv')
  expect(await readFile((await downloaded.path())!, 'utf8')).toContain('matched_order_value,GHS,1122800,11228.00')
  await page.screenshot({ path: 'test-results/reports-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('link', { name: 'Imports', exact: true }).click()
  await expect(page.getByRole('link', { name: /Download .* template/ })).toBeVisible()
  const narrowLayout = await page.evaluate(() => ({
    viewport: innerWidth,
    document: document.documentElement.scrollWidth,
    overflowing: Array.from(document.querySelectorAll('*')).filter(element => element.getBoundingClientRect().right > innerWidth + 1).slice(0, 12).map(element => ({ tag: element.tagName, className: element.className, right: element.getBoundingClientRect().right })),
  }))
  expect(narrowLayout.document, JSON.stringify(narrowLayout.overflowing)).toBeLessThanOrEqual(narrowLayout.viewport)
  await page.screenshot({ path: 'test-results/imports-mobile.png', fullPage: true })
  expect(browserErrors).toEqual([])
})
