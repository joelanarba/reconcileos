import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import path from 'node:path'

test('judge can inspect synthetic evidence and export results without an account', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const expected = JSON.parse(await readFile(path.resolve('../sample-data/demo/expected-results.json'), 'utf8'))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Find the payment differences your records missed.' })).toBeVisible()
  await expect(page.locator('.public-source-counts')).toContainText('100')
  await page.screenshot({ path: '../deploy/.local/landing-desktop.png', fullPage: true })
  expect((await page.request.get('/api/workspace')).status()).toBe(401)
  const data = await (await page.request.get('/api/demo/dashboard')).json()
  expect(data.latest_run.original_summary).toEqual(expected.summary)
  expect((await page.request.post('/api/demo/runs')).status()).toBeGreaterThanOrEqual(400)
  await page.getByRole('navigation', { name: 'Public navigation' }).getByRole('link', { name: 'Try the demo' }).click()
  await expect(page).toHaveURL(/\/demo\/dashboard$/)
  await expect(page.getByRole('heading', { name: 'Dashboard', exact: true })).toBeVisible()
  await expect(page.locator('.source-coverage')).toContainText('100')
  await page.getByText('Take a two-minute tour', { exact: true }).click()
  await expect(page.getByRole('link', { name: 'Read a saved AI investigation' })).toBeVisible()
  await page.screenshot({ path: '../deploy/.local/demo-dashboard.png', fullPage: true })
  const nav = page.getByRole('navigation', { name: 'Main navigation' })
  await nav.getByRole('link', { name: 'Reconciliation', exact: true }).click()
  await expect(page.getByRole('tab', { name: 'Review cases 54' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Start reconciliation' })).toHaveCount(0)
  await page.getByRole('button', { name: 'View evidence' }).first().click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('dialog').getByRole('link', { name: 'Open investigation' }).click()
  await expect(page.locator('.case-panel')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Resolve case' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Request AI assistance' })).toHaveCount(0)
  await page.locator('.evidence-record').first().getByText('Source and import history').click()
  await page.locator('.evidence-record').first().getByRole('link', { name: 'Open import provenance' }).click()
  await expect(page.getByRole('heading', { name: 'Imported evidence' })).toBeVisible()
  await expect(page.getByRole('columnheader', { name: 'Source row', exact: true })).toBeVisible()
  await nav.getByRole('link', { name: 'Dashboard', exact: true }).click()
  await page.getByRole('link', { name: 'Read a saved AI investigation' }).click()
  await expect(page.getByRole('heading', { name: 'Saved AI investigation' })).toBeVisible()
  await page.screenshot({ path: '../deploy/.local/demo-investigation.png', fullPage: true })
  await nav.getByRole('link', { name: 'Reports', exact: true }).click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export cases CSV' }).click()
  const file = await download
  const csv = await readFile((await file.path())!, 'utf8')
  expect(csv).toContain('partial_payment')
  expect(csv).toContain('missing_settlement_evidence')
  expect(await page.evaluate(() => sessionStorage.getItem('reconcileos.auth.session'))).toBeNull()
  await page.getByRole('link', { name: 'Exit demo' }).click()
  await page.getByRole('navigation', { name: 'Public navigation' }).getByRole('link', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Username', exact: true })).toBeVisible()
  await page.screenshot({ path: '../deploy/.local/login-desktop.png', fullPage: true })
  expect(errors).toEqual([])
})

